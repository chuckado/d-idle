package main

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

var verbRe = regexp.MustCompile(`^(F\d+)`)

func catalogue(root string) error {
	steps, err := boardSteps(root)
	if err != nil {
		return err
	}
	var sp Spec
	if err := readJSON(filepath.Join(root, "data/stepgrounds/steps.json"), &sp); err != nil {
		return err
	}
	var ver Verdicts
	if err := readJSON(filepath.Join(root, "data/stepgrounds/verdicts.json"), &ver); err != nil {
		return err
	}
	by := map[string]StepSpec{}
	for _, r := range sp.Steps {
		by[r.ID] = r
	}
	counts := map[string]int{}
	verbs := map[string]int{}
	var rows []string
	for _, st := range steps {
		r := by[st.key()]
		var scen, verdict, note string
		switch {
		case r.Scenario != "":
			scen, verdict = r.Scenario, verdictOf(ver, r.Scenario)
			counts["step"]++
		case r.Gen != nil:
			scen = scenarioID(st)
			verdict = verdictOf(ver, scen)
			counts["step"]++
		case len(r.Chunk) > 0:
			scen, verdict = "chunk: "+strings.Join(r.Chunk, ", "), verdictOf(ver, r.Chunk[0])
			counts["chunk"]++
		default:
			scen, verdict, note = "MISSING", "BLOCKED", r.Missing
			counts["missing"]++
			if m := verbRe.FindString(r.Missing); m != "" {
				verbs[m]++
			} else {
				verbs[strings.SplitN(r.Missing, ":", 2)[0]]++
			}
		}
		counts[verdict]++
		if v, ok := ver[scen]; ok && v.Run != "" {
			note += " [" + v.Tag + " run " + v.Run + "] " + v.Note
		}
		for _, a := range r.Also {
			note += " also " + a + " " + verdictOf(ver, a) + ";"
		}
		if r.Note != "" {
			if note != "" {
				note += " "
			}
			note += r.Note
		}
		rows = append(rows, fmt.Sprintf("| %d | `%s` | %s | %s | %s |", st.Act, st.key(), scen, verdict, strings.ReplaceAll(note, "|", "/")))
	}
	var b strings.Builder
	b.WriteString("# Quest step catalogue (generated)\n\n> status: current. GENERATED by `go run ./cmd/stepcat catalogue` from `data/questboard/act1..5.json`, `data/stepgrounds/steps.json` and `data/stepgrounds/verdicts.json`; `go run ./cmd/stepcat check` (and its Go test) fails when a step has neither a scenario nor an explicit MISSING reason. Every setup is CHEATED (lab verbs): the verdicts are about mechanics, never about the live hero. Tags: V a named run, U unrun or unread.\n\n")
	fmt.Fprintf(&b, "Steps total %d: step scenario %d (generated or hand-written), only a chunk-level scenario %d, MISSING %d.\n\n", len(steps), counts["step"], counts["chunk"], counts["missing"])
	fmt.Fprintf(&b, "Verdicts: GREEN %d, RED %d, BLOCKED %d (every MISSING step counts as BLOCKED), PENDING %d (a scenario that was never run).\n\n", counts["GREEN"], counts["RED"], counts["BLOCKED"], counts["PENDING"])
	var ks []string
	for k := range verbs {
		ks = append(ks, k)
	}
	sort.Strings(ks)
	b.WriteString("MISSING by cause:")
	for _, k := range ks {
		fmt.Fprintf(&b, " %s %d;", k, verbs[k])
	}
	b.WriteString(" (F<n> is a fork verb request, docs/probes/stepgrounds-fork-request.md; bot is a bot or scenario-format gap; data is missing data.)\n\n")
	b.WriteString("| act | step (quest/chunk/step) | scenario | verdict | note |\n|---|---|---|---|---|\n")
	b.WriteString(strings.Join(rows, "\n") + "\n")
	return os.WriteFile(filepath.Join(root, "docs/probes/quest-step-catalogue.md"), []byte(b.String()), 0o644)
}

func verdictOf(v Verdicts, id string) string {
	if r, ok := v[id]; ok {
		return r.Verdict
	}
	return "PENDING"
}
