package main

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

func areaIDs(root string) (map[string]int, error) {
	var d struct {
		Areas []struct {
			ID   int    `json:"id"`
			Name string `json:"name"`
		} `json:"areas"`
	}
	if err := readJSON(filepath.Join(root, "internal/plandata/areas.json"), &d); err != nil {
		return nil, err
	}
	m := map[string]int{}
	for _, a := range d.Areas {
		m[a.Name] = a.ID
	}
	return m, nil
}

func clone(m map[string]any) map[string]any {
	b, _ := json.Marshal(m)
	var o map[string]any
	_ = json.Unmarshal(b, &o)
	if o == nil {
		o = map[string]any{}
	}
	return o
}

func actionOf(step string) string {
	switch {
	case strings.HasPrefix(step, "travel_"), strings.HasPrefix(step, "enter_"), strings.HasPrefix(step, "descend_"):
		return "travel"
	case strings.HasPrefix(step, "kill_"), strings.HasPrefix(step, "clear_"):
		return "kill"
	case strings.HasPrefix(step, "take_"):
		return "interact"
	}
	return "interact"
}

// scenarioID is the id of a generated scenario: step.act<N>.<quest>.<chunk>.<step>.
func scenarioID(st step) string {
	return fmt.Sprintf("step.act%d.%s.%s.%s", st.Act, st.Quest, st.Chunk, st.Step)
}

func gen(root string) error {
	steps, err := boardSteps(root)
	if err != nil {
		return err
	}
	var sp Spec
	if err := readJSON(filepath.Join(root, "data/stepgrounds/steps.json"), &sp); err != nil {
		return err
	}
	areas, err := areaIDs(root)
	if err != nil {
		return err
	}
	byKey := map[string]step{}
	for _, s := range steps {
		byKey[s.key()] = s
	}
	var out []map[string]any
	for _, row := range sp.Steps {
		if row.Gen == nil {
			continue
		}
		st, ok := byKey[row.ID]
		if !ok {
			return fmt.Errorf("spec row %s is not a board step", row.ID)
		}
		g := row.Gen
		pre := clone(asMap(sp.Kit["pre"]))
		trig := clone(asMap(sp.Kit["trigger"]))
		if g.Start != "" {
			id, ok := areas[g.Start]
			if !ok {
				return fmt.Errorf("%s: unknown area %q (internal/plandata/areas.json)", row.ID, g.Start)
			}
			pre["start"], pre["area"] = "field", id
		}
		if len(g.Quests) > 0 {
			pre["quests"] = g.Quests
		}
		var items []any
		for _, c := range g.Ground {
			items = append(items, map[string]any{"code": c, "where": "ground", "quality": 2})
		}
		for _, c := range g.Pack {
			items = append(items, map[string]any{"code": c})
		}
		if base, ok := pre["items"].([]any); ok {
			items = append(base, items...)
		}
		if len(items) > 0 {
			pre["items"] = items
		}
		if len(g.Spawn) > 0 {
			pre["spawn"] = g.Spawn
		}
		if g.Goals != "" {
			trig["goals"] = g.Goals
		} else {
			pre["board"] = map[string]any{"quest": st.Quest, "chunk": st.Chunk}
		}
		asserts := []any{map[string]any{"kind": "log_line", "pattern": "^character died ", "max": 0, "why": "no death"}}
		if g.Enter != "" {
			asserts = append(asserts, map[string]any{"kind": "log_line", "pattern": "^Entered " + g.Enter, "min": 1, "why": "the bot logged the area change (S: the bot's own report)"})
		}
		if g.Kill != "" {
			asserts = append(asserts, map[string]any{"kind": "log_line", "pattern": "^combat kill .*monster=" + g.Kill, "min": 1, "why": "the bot killed it (S: the bot's own report)"})
		}
		if g.Kills > 0 {
			asserts = append(asserts, map[string]any{"kind": "log_line", "pattern": "^combat kill ", "min": g.Kills, "why": "the bot fought here (S: the bot's own report)"})
		}
		if g.Picked != "" {
			asserts = append(asserts, map[string]any{"kind": "log_line", "pattern": "^loot: clicked .*item=" + g.Picked, "min": 1, "why": "the bot clicked the item on the ground (S)"})
		}
		budget := g.Budget
		if budget == 0 {
			budget = 8
		}
		s := map[string]any{
			"id": scenarioID(st), "title": "Step ground " + row.ID, "kind": "step", "tier": "full",
			"quest":      map[string]any{"quest": st.Quest, "chunk": st.Chunk},
			"step":       map[string]any{"action": actionOf(st.Step), "target": st.Step},
			"covers":     []string{"quest." + st.Quest + "." + st.Chunk},
			"pre":        pre,
			"trigger":    trig,
			"budget":     map[string]any{"virtual_min": budget},
			"assert":     asserts,
			"matrix":     sp.Kit["matrix"],
			"needs":      []string{"lab-verbs-attach"},
			"provenance": sp.Kit["provenance"],
			"notes":      "Generated by cmd/stepcat from data/stepgrounds/steps.json; edit the data, not this file. " + row.Note,
		}
		if g.Pending != "" {
			s["status"], s["pending_reason"] = "pending", g.Pending
		}
		out = append(out, s)
	}
	b, err := json.MarshalIndent(map[string]any{"version": "didle.scenario/1", "scenarios": out}, "", " ")
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(root, "tools/provingground/scenarios/stepgrounds_gen.json"), append(b, '\n'), 0o644)
}

func asMap(v any) map[string]any {
	m, _ := v.(map[string]any)
	return m
}
